# Database - PostgreSQL (Neon, Supabase, Railway) or SQLite
DATABASE_URL = os.environ.get('DATABASE_URL')
if DATABASE_URL:
    DATABASES = {
        'default': dj_database_url.config(
            default=DATABASE_URL,
            conn_max_age=600,
            conn_health_checks=True,
        )
    }
elif os.environ.get('DB_ENGINE') == 'django.db.backends.postgresql':
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': os.environ.get('DB_NAME', 'learnsphere'),
            'USER': os.environ.get('DB_USER', 'postgres'),
            'PASSWORD': os.environ.get('DB_PASSWORD', ''),
            'HOST': os.environ.get('DB_HOST', 'localhost'),
            'PORT': os.environ.get('DB_PORT', '5432'),
        }
    }
else:
    # Handle Vercel serverless read-only filesystem by copying seeded db to /tmp
    db_file = BASE_DIR / 'db.sqlite3'
    if os.environ.get('VERCEL'):
        import shutil
        tmp_db = Path('/tmp') / 'db.sqlite3'
        if not tmp_db.exists() and db_file.exists():
            try:
                shutil.copy2(db_file, tmp_db)
            except Exception:
                pass
        if tmp_db.exists():
            db_file = tmp_db

    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': db_file,
        }
    }

